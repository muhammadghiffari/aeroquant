SCHEMA_VERSION = "2.6.0"
MAX_REPAIR_HOPS = 3  # Bounded repair loop — hard limit, not LLM-controlled


def _merge_provider_usage(
    existing: dict[str, str], incoming: dict[str, str]
) -> dict[str, str]:
    """Merge independent parallel-agent telemetry without shared mutation."""
    return {**existing, **incoming}


def _merge_failure_text(existing: str, incoming: str) -> str:
    """Retain all simultaneous branch failures instead of overwriting one."""
    if not existing:
        return incoming
    if not incoming or incoming in existing:
        return existing
    return f"{existing}; {incoming}"


class CyclePhase(str, Enum):
    """The current phase/step of the cycle — used for telemetry and crash recovery."""

    PENDING = "pending"
    PRECHECK = "precheck"
    EVIDENCE = "evidence"
    QUANT = "quant"
    CANDIDATES = "candidates"
    MEMORY = "memory"
    VOLATILITY = "volatility"
    MACRO = "macro"
    TECHNICAL = "technical"
    BULL = "bull"
    BEAR = "bear"
    CHIEF = "chief"
    VALIDATOR = "validator"
    RISK_GATE = "risk_gate"
    PERSIST = "persist"
    COMPLETE = "complete"
    FAILED = "failed"


def _merge_phase(existing: CyclePhase, incoming: CyclePhase) -> CyclePhase:
    """Fail closed when parallel branches report different terminal phases."""
    if existing == CyclePhase.FAILED or incoming == CyclePhase.FAILED:
        return CyclePhase.FAILED
    return incoming


class CandidateReadiness(str, Enum):
    """Whether the candidate boundary supplied executable market contracts."""

    READY = "ready"
    NOT_READY = "not_ready"



class ChiefReport(BaseModel):
    """Chief's qualitative selection of a CandidateBuilder proposal.

    Contract selection, prices, DTE, sizing, and risk values remain locked in
    ``ValidatedCandidate.proposal`` and are never generated by the Chief.
    """

    model_config = {"extra": "forbid"}

    proposal_id: str
    side: Literal["iron_condor", "bull_put_spread", "bear_call_spread", "skip"] = "skip"
    rationale: str = ""
    confidence: float = Field(ge=0.0, le=1.0)
    provider: str = ""

    def to_dict(self) -> dict:
        return self.model_dump()


class ValidatorReport(BaseModel):
    """Output of the proposal validator."""

    valid: bool = False
    errors: list[str] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)
    suggested_fix: str = ""

    def to_dict(self) -> dict:
        return self.model_dump()


class CandidateProvenance(BaseModel):
    """Provenance required before a candidate may be evaluated by RiskManager."""

    model_config = {"extra": "forbid"}

    source: Literal["alpaca_options_chain"]
    data_tier: Literal["indicative", "opra"]
    underlying_symbol: str = Field(min_length=1)
    snapshot_timestamp: datetime
    contract_snapshot_id: str = Field(min_length=1)


class ValidatedCandidate(BaseModel):
    """A deterministic, options-chain-backed proposal supplied by CandidateBuilder.

    The Chief may select this object by ``proposal_id`` but never supplies or
    modifies its contracts, prices, account context, or risk values.
    """

    model_config = {"extra": "forbid"}

    proposal: "TradeProposal"
    provenance: CandidateProvenance

    @property
    def proposal_id(self) -> str:
        return self.proposal.proposal_id



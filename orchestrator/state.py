"""
orchestrator/state.py — CycleState: the strongly-typed state schema for the LangGraph.

PRD §5.4 / RUNBOOK §12:
  - Every state field is account-scoped via alpaca_account_id.
  - thread_id = f"{alpaca_account_id}:{cycle_id}" (enforced at the checkpointer
    level, not inside state itself).
  - Bounded chief ↔ validator repair loop via repair_hop counter.
  - No credentials, API keys, or passwords in state.
"""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Annotated, Literal

from pydantic import BaseModel, Field, model_validator

# Runtime imports for Pydantic get_type_hints() resolution.

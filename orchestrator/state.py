class CycleState(BaseModel):
    """
    Strongly-typed state for the AeroQuant LangGraph.

    Field design principles:
      - Only fields that change during the graph traversal are mutable (no defaults
        for required fields — they must be set by the appropriate node).
      - No credentials, API keys, or passwords.
      - repair_hop is the bounded repair-loop counter (PRD §5.4).
      - phase tracks the current step for crash recovery.
    """

    model_config = {"extra": "forbid"}

    # ---- Identity ----
    alpaca_account_id: str = Field(
        min_length=1,
        description="Alpaca account ID — used for thread_id and all persistence",
    )
    cycle_id: str = Field(
        min_length=1,
        description="Unique cycle ID (UUID or timestamp-based)",
    )

    # ---- Phase tracking ----
    phase: Annotated[CyclePhase, _merge_phase] = Field(default=CyclePhase.PENDING)
    started_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc)
    )
    completed_at: datetime | None = None

    # ---- Precheck ----
    precheck_passed: bool = False
    precheck_reason: str = ""

    # ---- Evidence / Data ----
    evidence: dict = Field(
        default_factory=dict,
        description="Raw market data snapshot (spot, IV, chain, news)"
    )

    # ---- Quant Engine output ----
    quant_metrics: "QuantMetrics | None" = Field(
        default=None,
        description="All §5.1 deterministic metrics from QuantEngine"
    )
    evidence_envelope: "EvidenceEnvelope | None" = None

    # ---- Candidate generation ----
    candidate_readiness: CandidateReadiness = CandidateReadiness.NOT_READY
    candidate_reason: str = "CandidateBuilder has not supplied a validated candidate"
    candidates: list[ValidatedCandidate] = Field(
        default_factory=list,
        description="Validated options-chain candidates from CandidateBuilder",
    )
    risk_proposal: "TradeProposal | None" = Field(
        default=None,
        description=(
            "Typed deterministic candidate selected by Chief. CandidateBuilder, not "
            "an LLM node, supplies contracts, prices, and account-risk context."
        ),
    )

    # ---- Memory context (per-cycle working memory) ----
    memory_context: dict = Field(
        default_factory=dict,
        description="Working memory: episodic retrieval, semantic rules, recent cycles"
    )

    # ---- LLM branch outputs ----
    volatility_report: "VolatilityReport | None" = None
    macro_report: "MacroReport | None" = None
    technical_report: "TechnicalReport | None" = None
    bull_report: "BullBearReport | None" = None
    bear_report: "BullBearReport | None" = None
    chief_report: "ChiefReport | None" = None
    validator_report: "ValidatorReport | None" = None

    # ---- Chief selection (the report is qualitative; risk_proposal is immutable data-plane input) ----
    selected_candidate_id: str | None = None
    candidate_selection_error: str = ""

    # ---- Risk Gate ----
    risk_decision: "RiskDecision | None" = None

    # ---- Persistence ----
    persisted: bool = False
    persist_error: str = ""

    # ---- Repair loop ----
    repair_hop: int = Field(
        default=0,
        ge=0,
        le=MAX_REPAIR_HOPS,
        description=f"Bounded repair hop counter. Max {MAX_REPAIR_HOPS}. "
                    "Chief ↔ Validator loop only."
    )

    # ---- Error / failure state ----
    error: Annotated[str, _merge_failure_text] = Field(
        default="",
        description="Human-readable error message if phase == FAILED"
    )
    failed_node: Annotated[str, _merge_failure_text] = Field(
        default="",
        description="Which node raised the error"
    )

    # ---- Telemetry ----
    provider_used: Annotated[dict[str, str], _merge_provider_usage] = Field(
        default_factory=dict,
        description="Which provider served each LLM call: {node: provider_name}"
    )

    @model_validator(mode="after")
    def _reject_secrets_in_untyped_context(self) -> "CycleState":
        """Keep raw evidence/memory containers from becoming credential stores."""
        prohibited = {
            "api_key",
            "api_secret",
            "password",
            "credentials",
            "provider_credentials",
            "access_token",
            "refresh_token",
        }

        def inspect(value: object) -> None:
            if isinstance(value, dict):
                for key, nested in value.items():
                    if str(key).lower() in prohibited:
                        raise ValueError("CycleState must not contain credentials or secrets")
                    inspect(nested)
            elif isinstance(value, list):
                for nested in value:
                    inspect(nested)

        inspect(self.evidence)
        inspect(self.memory_context)
        return self

    def to_thread_id(self) -> str:
        """
        Account-scoped thread_id per PRD §5.4.

        Must be used as the checkpointer thread_id — never cycle_id alone.
        """
        return f"{self.alpaca_account_id}:{self.cycle_id}"

    def next_phase(self, next_phase: CyclePhase) -> "CycleState":
        """Return a copy with the phase updated (immutable update pattern)."""
        return self.model_copy(deep=True, update={"phase": next_phase})

    def advance_repair_hop(self) -> "CycleState":
        """Return a copy with repair_hop incremented."""
        if self.repair_hop >= MAX_REPAIR_HOPS:
            return self.model_copy(deep=True)
        return self.model_copy(
            deep=True,
            update={"repair_hop": self.repair_hop + 1}
        )

    @property
    def at_max_repair_hops(self) -> bool:
        return self.repair_hop >= MAX_REPAIR_HOPS

    def is_failure(self) -> bool:
        return self.phase == CyclePhase.FAILED or bool(self.error)
